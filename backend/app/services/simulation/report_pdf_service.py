"""ReportPDFService — PDF export for simulation reports.

Uses reportlab to generate professional PDF reports from structured
report data. This is a presentation layer — it never recalculates
simulation results.
"""

from __future__ import annotations

from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    BaseDocTemplate,
    Frame,
    NextPageTemplate,
    PageBreak,
    PageTemplate,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


class ReportPDFService:
    """Generates PDF documents from simulation report data."""

    def __init__(self) -> None:
        self._styles = getSampleStyleSheet()
        self._register_custom_styles()

    def _register_custom_styles(self) -> None:
        self._styles.add(ParagraphStyle(
            "ReportTitle",
            parent=self._styles["Title"],
            fontSize=18,
            spaceAfter=12,
            alignment=TA_CENTER,
        ))
        self._styles.add(ParagraphStyle(
            "SectionHeader",
            parent=self._styles["Heading2"],
            fontSize=14,
            spaceBefore=16,
            spaceAfter=8,
            textColor=colors.HexColor("#1a365d"),
        ))
        self._styles.add(ParagraphStyle(
            "SubSection",
            parent=self._styles["Heading3"],
            fontSize=12,
            spaceBefore=10,
            spaceAfter=6,
        ))
        self._styles.add(ParagraphStyle(
            "BodyText2",
            parent=self._styles["BodyText"],
            fontSize=10,
            spaceAfter=6,
        ))
        self._styles.add(ParagraphStyle(
            "Disclaimer",
            parent=self._styles["BodyText"],
            fontSize=9,
            textColor=colors.HexColor("#666666"),
            spaceBefore=12,
            spaceAfter=6,
            borderWidth=1,
            borderColor=colors.HexColor("#cccccc"),
            borderPadding=6,
        ))

    def generate(self, report) -> bytes:
        """Generate PDF bytes from a SimulationReportResponse."""
        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            rightMargin=50,
            leftMargin=50,
            topMargin=50,
            bottomMargin=50,
        )

        story = []
        data = report.report_data or {}

        # ── Title Page ──
        story.append(Spacer(1, 1 * inch))
        story.append(Paragraph(
            data.get("header", {}).get("title", "Simulation Report"),
            self._styles["ReportTitle"],
        ))
        story.append(Spacer(1, 0.3 * inch))

        # Metadata
        header = data.get("header", {})
        meta_lines = [
            f"Report Type: {header.get('report_type', 'N/A')}",
            f"Job: {header.get('job_title', 'N/A')}",
            f"Scenario: {header.get('scenario_name', 'N/A')}",
            f"Generated By: {header.get('generated_by', 'N/A')}",
            f"Generated At: {header.get('generated_at', 'N/A')}",
            f"Report Version: {header.get('report_version', '1.0')}",
        ]
        for line in meta_lines:
            story.append(Paragraph(line, self._styles["BodyText2"]))

        story.append(Spacer(1, 0.3 * inch))

        # Disclaimer
        limitations = data.get("limitations", {})
        disclaimer = limitations.get(
            "simulation_isolation_notice",
            "What-if Analysis: These results represent a hypothetical simulation.",
        )
        story.append(Paragraph(disclaimer, self._styles["Disclaimer"]))
        story.append(PageBreak())

        # ── Executive Summary ──
        exec_summary = data.get("executive_summary", {})
        if exec_summary:
            story.append(Paragraph("Executive Summary", self._styles["SectionHeader"]))
            story.append(Paragraph(
                exec_summary.get("narrative", ""),
                self._styles["BodyText2"],
            ))
            changes = exec_summary.get("key_configuration_changes", [])
            if changes:
                story.append(Paragraph("Key Configuration Changes:", self._styles["SubSection"]))
                for change in changes:
                    story.append(Paragraph(f"  • {change}", self._styles["BodyText2"]))
            story.append(Spacer(1, 0.2 * inch))

        # ── Configuration Diff ──
        config_diff = data.get("configuration_diff", {})
        if config_diff:
            story.append(Paragraph("Configuration Comparison", self._styles["SectionHeader"]))
            weights = config_diff.get("weights", [])
            if weights:
                table_data = [["Weight", "Baseline", "Simulation", "Change"]]
                for w in weights:
                    table_data.append([
                        w.get("weight_label", ""),
                        f"{w.get('baseline', 0) * 100:.0f}%",
                        f"{w.get('simulation', 0) * 100:.0f}%",
                        w.get("change_label", "0"),
                    ])
                table = Table(table_data, colWidths=[2 * inch, 1.5 * inch, 1.5 * inch, 1.5 * inch])
                table.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1a365d")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                    ("GRID", (0, 0), (-1, -1), 1, colors.grey),
                    ("FONTSIZE", (0, 0), (-1, -1), 9),
                    ("BOTTOMPADDING", (0, 0), (-1, 0), 8),
                    ("TOPPADDING", (0, 0), (-1, 0), 8),
                ]))
                story.append(table)

            threshold = config_diff.get("threshold")
            if threshold:
                story.append(Spacer(1, 0.1 * inch))
                story.append(Paragraph(
                    f"Threshold: {threshold.get('baseline')} → {threshold.get('simulation')} "
                    f"({threshold.get('change_label', '')})",
                    self._styles["BodyText2"],
                ))

            shortlist = config_diff.get("shortlist_size")
            if shortlist:
                story.append(Paragraph(
                    f"Shortlist Size: {shortlist.get('baseline')} → {shortlist.get('simulation')} "
                    f"({shortlist.get('change_label', '')})",
                    self._styles["BodyText2"],
                ))

            req_changes = config_diff.get("requirement_changes", [])
            if req_changes:
                story.append(Paragraph("Requirement Changes:", self._styles["SubSection"]))
                for rc in req_changes:
                    story.append(Paragraph(
                        f"  {rc.get('skill', '')}: {rc.get('from_status', '')} → {rc.get('to_status', '')}",
                        self._styles["BodyText2"],
                    ))
            story.append(Spacer(1, 0.2 * inch))

        # ── Candidate Impact ──
        candidate_impact = data.get("candidate_impact", {})
        if candidate_impact and candidate_impact.get("total_candidates", 0) > 0:
            story.append(Paragraph("Candidate Impact", self._styles["SectionHeader"]))
            story.append(Paragraph(
                f"Candidates evaluated: {candidate_impact.get('total_candidates', 0)}",
                self._styles["BodyText2"],
            ))
            story.append(Paragraph(
                f"Average score change: {candidate_impact.get('average_score_change', 0):+.2f}",
                self._styles["BodyText2"],
            ))
            story.append(Paragraph(
                f"Shortlist changes: {candidate_impact.get('candidates_entering_shortlist', 0)} entered, "
                f"{candidate_impact.get('candidates_leaving_shortlist', 0)} left",
                self._styles["BodyText2"],
            ))
            story.append(Spacer(1, 0.2 * inch))

        # ── Ranking Impact ──
        ranking = data.get("ranking_impact", {})
        if ranking and ranking.get("overview"):
            story.append(Paragraph("Ranking Impact", self._styles["SectionHeader"]))
            overview = ranking["overview"]
            story.append(Paragraph(
                f"Candidates moved up: {overview.get('candidates_moved_up', 0)}",
                self._styles["BodyText2"],
            ))
            story.append(Paragraph(
                f"Candidates moved down: {overview.get('candidates_moved_down', 0)}",
                self._styles["BodyText2"],
            ))
            story.append(Paragraph(
                f"Candidates unchanged: {overview.get('candidates_unchanged', 0)}",
                self._styles["BodyText2"],
            ))
            story.append(Spacer(1, 0.2 * inch))

        # ── Threshold Impact ──
        threshold = data.get("threshold_impact", {})
        if threshold and threshold.get("baseline_threshold"):
            story.append(Paragraph("Threshold Impact", self._styles["SectionHeader"]))
            story.append(Paragraph(
                f"Baseline threshold: {threshold.get('baseline_threshold')}, "
                f"Simulation threshold: {threshold.get('simulation_threshold')}",
                self._styles["BodyText2"],
            ))
            story.append(Paragraph(
                f"Newly qualified: {threshold.get('newly_qualified', 0)}, "
                f"Newly disqualified: {threshold.get('newly_disqualified', 0)}",
                self._styles["BodyText2"],
            ))
            story.append(Spacer(1, 0.2 * inch))

        # ── Shortlist Impact ──
        shortlist = data.get("shortlist_impact", {})
        if shortlist and shortlist.get("baseline_shortlist_size"):
            story.append(Paragraph("Shortlist Impact", self._styles["SectionHeader"]))
            story.append(Paragraph(
                f"Baseline shortlist: {shortlist.get('baseline_shortlist_size')}, "
                f"Simulation shortlist: {shortlist.get('simulation_shortlist_size')}",
                self._styles["BodyText2"],
            ))
            story.append(Paragraph(
                f"Retained: {shortlist.get('retained', 0)}, "
                f"Entering: {shortlist.get('entering', 0)}, "
                f"Leaving: {shortlist.get('leaving', 0)}",
                self._styles["BodyText2"],
            ))
            story.append(Spacer(1, 0.2 * inch))

        # ── Fairness Impact ──
        fairness = data.get("fairness_impact", {})
        if fairness and fairness.get("available"):
            story.append(Paragraph("Fairness Impact", self._styles["SectionHeader"]))
            groups = fairness.get("groups", [])
            if groups:
                story.append(Paragraph(
                    f"Fairness data available for {len(groups)} group(s).",
                    self._styles["BodyText2"],
                ))
            else:
                story.append(Paragraph(
                    "Fairness data available but no group-level data found.",
                    self._styles["BodyText2"],
                ))
            story.append(Spacer(1, 0.2 * inch))

        # ── Limitations ──
        limitations = data.get("limitations", {})
        if limitations and limitations.get("items"):
            story.append(Paragraph("Limitations", self._styles["SectionHeader"]))
            for item in limitations["items"]:
                story.append(Paragraph(f"  • {item}", self._styles["BodyText2"]))
            story.append(Spacer(1, 0.2 * inch))

        # ── Audit Info ──
        audit = data.get("audit_info", {})
        if audit:
            story.append(Paragraph("Audit Information", self._styles["SectionHeader"]))
            story.append(Paragraph(
                f"Report ID: {audit.get('report_id', 'N/A')}",
                self._styles["BodyText2"],
            ))
            story.append(Paragraph(
                f"Generated by: {audit.get('generated_by', 'N/A')}",
                self._styles["BodyText2"],
            ))
            story.append(Paragraph(
                f"Engine version: {audit.get('engine_version', 'N/A')}",
                self._styles["BodyText2"],
            ))

        doc.build(story)
        return buffer.getvalue()
